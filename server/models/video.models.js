const mongoose = require("mongoose");

const VideoData = mongoose.Schema(
  {
    title: {
      type: String,
      reruired: true,
    },
    videoUrl: {
      type: String,
      required: true,
    },
    publicId: {
      type: String,
      required: true,
    },
    size: {
      type: Number,
      required: true,
    },
    duration: {
      type: Number,
      required: true,
    },
  },
  {
    timestamps: true,
  },
); // here creted at will be generated by itself
const videoData = mongoose.model("videoData", VideoData);
module.export = {
  videoData,
};
