const mongoose = require("mongoose");

const VideoData = mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
    },
    videoUrl: {
      type: String,
      required: true,
    },
    publicId: {
      type: String,
    },
    size: {
      type: Number,
    },
    duration: {
      type: Number,
      default: 0,
    },
    thumbnailURL: {
      type: String,
      required: true,
    },
    description: {
      type: String,
      required: true,
    },
    transcript: {
      type: String,
    },
    segments: {
      type: [
        {
          start: Number,
          end: Number,
          text: String,
        },
      ],
    },
    transcriptionStatus: {
      type: String,
      enum: ["pending", "processing", "completed", "failed"],
      default: "pending",
    },
    summary: {
      type: String,
      default: null,
    },

    summaryStatus: {
      type: String,
      enum: ["pending", "processing", "completed", "failed"],
      default: "pending",
    },

    summaryGeneratedAt: {
      type: Date,
      default: null,
    },
  },

  {
    timestamps: true,
  },
); // here  at will be generated by itself
const Video = mongoose.model("Video", VideoData);
module.exports = Video;
