const mongoose = require("mongoose");

const VideoData = mongoose.Schema(
  {
    title: {
      type: String,
      reruired: true,
    },
    videoUrl: {
      type: String,
      required: true,
    },
    publicId: {
      type: String,
    },
    size: {
      type: Number,
    },
    duration: {
      type: Number,
      default: 0,
    },
    thumbnailURL: {
      type: String,
      required: true,
    },
  },
  {
    timestamps: true,
  },
); // here creted at will be generated by itself
const Video = mongoose.model("Video", VideoData);
module.exports = Video;
